'use strict'
const fs = require('node:fs')
const path = require('node:path')
const { execFileSync } = require('node:child_process')
const { buildIcon } = require('./icon.cjs')
const root = path.resolve(__dirname, '..')
if (process.platform !== 'linux' || process.arch !== 'x64') throw new Error('首版仅打包 Linux x64。')
buildIcon(path.join(root, 'assets/icon.png'))
const target = path.join(root, 'dist', 'Loom-linux-x64'), binary = path.dirname(require('electron'))
fs.rmSync(target, { recursive: true, force: true }); fs.mkdirSync(target, { recursive: true })
fs.cpSync(binary, target, { recursive: true })
fs.renameSync(path.join(target, 'electron'), path.join(target, 'loom'))
const app = path.join(target, 'resources', 'app')
fs.mkdirSync(app, { recursive: true })
for (const file of ['package.json', 'main.cjs', 'preload.cjs', 'runtime.cjs', 'policy.cjs', 'onboarding.cjs', 'smoke.cjs', 'setup-smoke.cjs', 'ui', 'assets']) fs.cpSync(path.join(root, file), path.join(app, file), { recursive: true })
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')); delete pkg.devDependencies; delete pkg.scripts
fs.writeFileSync(path.join(app, 'package.json'), JSON.stringify(pkg, null, 2))
fs.writeFileSync(path.join(app, 'runtime-defaults.json'), JSON.stringify({ backendRoot: path.dirname(root), serviceURL: 'http://127.0.0.1:3082' }, null, 2))
fs.copyFileSync(path.join(path.dirname(root), 'LICENSE'), path.join(target, 'LOOM-LICENSE'))
fs.writeFileSync(path.join(target, '使用说明.txt'), 'Loom Linux 本机接入版\n\n双击 loom 启动。自动连接当前 Superagent 项目和既有飞书、模型配置。\n关闭窗口后可从应用菜单重新打开；退出客户端不停止助手。\n本包不包含个人凭据、任务库或模型，也未内置 Harness/CLI 依赖。\n新设备须先配置本机个人助手，再在客户端选择项目目录。\n当前仅验证 Linux x64；手机和其他系统版本待后续适配。\n')
const archive = path.join(root, 'dist', `Loom-${pkg.version}-linux-x64.tar.gz`)
execFileSync('tar', ['-czf', archive, '-C', path.dirname(target), path.basename(target)], { timeout: 120_000 })
process.stdout.write(JSON.stringify({ directory: target, archive }, null, 2) + '\n')
